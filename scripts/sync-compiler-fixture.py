#!/usr/bin/env python3
"""Generate a test-only ABI boundary so legacy protocol fixtures execute the patched executor artifact."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check',action='store_true')
args=parser.parse_args()
source_path=Path('contracts/src/MarketRebalancer.sol')
artifact_path=Path('out/MarketRebalancer.sol/MarketRebalancer.json')
source=source_path.read_text()
artifact=json.loads(artifact_path.read_text())
compiler=artifact['metadata']['compiler']['version']
if not compiler.startswith('0.8.37+'):
    raise SystemExit('Build the exact 0.8.37 executor before generating the test boundary')

def block(text,kind,name):
    match=re.search(r'\b'+kind+r'\s+'+name+r'\s*\{',text)
    if not match: raise RuntimeError('Missing declaration: '+name)
    depth=1;end=match.end()
    while depth:
        if text[end]=='{': depth+=1
        if text[end]=='}': depth-=1
        end+=1
    return text[match.start():end]

body=subprocess.check_output(['cast','interface',str(artifact_path),'--name','ICompilerRebalancer','--pragma','>=0.8.34 <0.9.0'],text=True)
# cast currently emits a globally named nested tuple inside the interface even though its library uses it.
# Lift exactly the generated PoolKey declaration; no ABI fields or wire types are changed.
pool=block(body,'struct','PoolKey')
body=body.replace(pool,'',1)
body=body.replace('library MarketRebalancer {',pool+'\n\nlibrary MarketRebalancer {',1)
extra='\n\n'.join(block(source,'struct',name) for name in ['ExactInputSingle','ExtendedExactInputSingle'])
body=body.replace('    type Venue is uint8;','    type Venue is uint8;\n'+extra,1)
body+='\n\n'+'\n\n'.join(block(source,'interface',name) for name in ['IV3Pool','IUniversalRouter','IPermit2'])+'\n'
body=body.replace('// SPDX-License-Identifier: UNLICENSED','// SPDX-License-Identifier: MIT',1)
body=body.replace('pragma solidity','// GENERATED by scripts/sync-compiler-fixture.py. Test types only; never a deployed executor.\npragma solidity',1)
# Format in memory for deterministic checked-in output, without rewriting anything in check mode.
body=subprocess.check_output(['forge','fmt','--raw','-'],input=body,text=True)
path=Path('contracts/test/generated/CompilerRebalancer.sol')
if args.check:
    if not path.exists() or path.read_text()!=body: raise SystemExit('Test ABI boundary is stale; regenerate it from the rebuilt executor')
else:
    path.parent.mkdir(parents=True,exist_ok=True);path.write_text(body)
print(json.dumps({'compiler':compiler,'sourceSha256':hashlib.sha256(source_path.read_bytes()).hexdigest(),'testBoundarySha256':hashlib.sha256(body.encode()).hexdigest(),'check':args.check}))
